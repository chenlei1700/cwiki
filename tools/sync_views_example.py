"""sync_views_example.py — reference skeleton for the L1 -> L2 sync pattern.

The "file housekeeper": regenerates Layer-2 derived views from Layer-1 SSOT.
See docs/maintenance-mechanisms.md (Mechanism 1) and templates/SCHEMA.md §3.

Contract this skeleton implements:
  - reads ONLY L1 (append-only ledger + machine-produced run artifacts)
  - rewrites the L2 file COMPLETELY (no merging; the script owns the file)
  - every L2 file starts with an explicit DO-NOT-EDIT marker
  - --check mode for pre-commit hooks: exit 1 if the on-disk L2 is stale
  - --dry-run mode: print what would be written

Usage:
  python tools/sync_views_example.py             # regenerate (overwrite)
  python tools/sync_views_example.py --check     # compare only; exit 1 if stale
  python tools/sync_views_example.py --dry-run   # print, don't write

Customize the CONFIG block and `render()` for your project; the mode handling
below them is the reusable part.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path

# ---------------------------------------------------------------- CONFIG --
# Customize these three for your project.
ROOT = Path(__file__).resolve().parents[1]          # project root
LEDGER = ROOT / "wiki" / "release_history.jsonl"    # L1: append-only ledger
VIEW = ROOT / "wiki" / "_current_state.md"          # L2: the derived view

MARKER = "<!-- AUTO-GENERATED by sync_views_example.py — DO NOT EDIT BY HAND -->"
# -------------------------------------------------------------------------


def load_ledger() -> list[dict]:
    """Read the append-only L1 ledger. Blank lines and '#' comments allowed."""
    if not LEDGER.exists():
        raise FileNotFoundError(f"L1 ledger not found: {LEDGER}")
    rows = []
    for line in LEDGER.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        rows.append(json.loads(line))
    if not rows:
        raise ValueError(f"ledger is empty: {LEDGER}")
    return rows


def render(rows: list[dict]) -> str:
    """Render the L2 view from L1 rows. Customize freely — but render from
    L1 data ONLY. If you are tempted to pull text from a narrative (L3) page,
    that text belongs here as a LINK, not as content (SCHEMA §3.3)."""
    latest = rows[-1]  # append-only: last row is current
    lines = [
        MARKER,
        "",
        "# Current State",
        "",
        f"> Synced {datetime.now():%Y-%m-%d %H:%M} from `{LEDGER.name}` "
        f"({len(rows)} rows). To change this file, append to the ledger and re-run sync.",
        "",
        "| Field | Value |",
        "|---|---|",
    ]
    for key in sorted(latest):
        lines.append(f"| {key} | {latest[key]} |")
    lines += [
        "",
        "## History",
        "",
    ]
    for row in reversed(rows[-10:]):
        ident = row.get("id") or row.get("version") or "?"
        date = row.get("date", "?")
        note = row.get("note", "")
        lines.append(f"- `{date}` **{ident}** {note}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the on-disk view is stale (for pre-commit)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print what would be written, don't write")
    args = ap.parse_args()

    fresh = render(load_ledger())

    if args.dry_run:
        print(fresh)
        return 0

    on_disk = VIEW.read_text(encoding="utf-8") if VIEW.exists() else ""

    if args.check:
        if on_disk == fresh:
            print(f"[sync --check] OK: {VIEW.relative_to(ROOT)} is current")
            return 0
        print(f"[sync --check] STALE: {VIEW.relative_to(ROOT)} does not match the ledger.",
              file=sys.stderr)
        print("  Fix: python tools/sync_views_example.py   (then re-commit)",
              file=sys.stderr)
        return 1

    if on_disk and not on_disk.startswith(MARKER):
        # Refuse to clobber a file that was never ours — somebody hand-wrote it.
        print(f"[sync] REFUSING to overwrite {VIEW}: missing DO-NOT-EDIT marker.\n"
              f"  If this file should become an L2 view, delete it once by hand.",
              file=sys.stderr)
        return 1

    VIEW.parent.mkdir(parents=True, exist_ok=True)
    VIEW.write_text(fresh, encoding="utf-8")
    print(f"[sync] wrote {VIEW.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
